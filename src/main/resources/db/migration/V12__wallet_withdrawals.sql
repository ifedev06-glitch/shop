CREATE TABLE withdrawal_bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    account_number_encrypted TEXT NOT NULL,
    account_number_last4 VARCHAR(4) NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(255) NOT NULL,
    account_name VARCHAR(255) NOT NULL,
    payout_recipient_code VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_withdrawal_bank_account_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX idx_withdrawal_bank_accounts_user_id
    ON withdrawal_bank_accounts (user_id);

CREATE TABLE wallet_withdrawals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    reference VARCHAR(80) NOT NULL UNIQUE,
    transfer_id VARCHAR(100),
    payout_recipient_code VARCHAR(100) NOT NULL,
    account_number_last4 VARCHAR(4) NOT NULL,
    bank_name VARCHAR(255) NOT NULL,
    account_name VARCHAR(255) NOT NULL,
    dispatch_attempt INTEGER NOT NULL DEFAULT 0,
    failure_reason VARCHAR(255),
    provider_updated_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wallet_withdrawal_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id),
    CONSTRAINT uq_wallet_withdrawal_key UNIQUE (wallet_id, idempotency_key)
);

CREATE INDEX idx_wallet_withdrawals_wallet_created
    ON wallet_withdrawals (wallet_id, created_at);
CREATE UNIQUE INDEX idx_wallet_withdrawals_reference
    ON wallet_withdrawals (reference);

ALTER TABLE wallet_transactions ADD COLUMN withdrawal_id BIGINT;
ALTER TABLE wallet_transactions
    ADD CONSTRAINT fk_wallet_transaction_withdrawal
    FOREIGN KEY (withdrawal_id) REFERENCES wallet_withdrawals (id);
CREATE INDEX idx_wallet_transactions_withdrawal_id
    ON wallet_transactions (withdrawal_id);
CREATE UNIQUE INDEX idx_wallet_transactions_withdrawal_type
    ON wallet_transactions (withdrawal_id, transaction_type);
