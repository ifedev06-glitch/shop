CREATE TABLE waybills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    creator_id BIGINT NOT NULL,
    creation_idempotency_key VARCHAR(255) NOT NULL,
    creation_request_hash VARCHAR(64) NOT NULL,
    creator_role VARCHAR(20) NOT NULL,
    payer_type VARCHAR(30) NOT NULL,
    description TEXT NOT NULL,
    declared_value NUMERIC(38, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',
    status VARCHAR(40) NOT NULL DEFAULT 'AWAITING_PARTY_DETAILS',
    payment_status VARCHAR(40) NOT NULL DEFAULT 'NOT_STARTED',
    provider_delivery_fee NUMERIC(38, 2),
    delivery_markup NUMERIC(38, 2),
    delivery_fee NUMERIC(38, 2),
    service_fee NUMERIC(38, 2),
    total_amount NUMERIC(38, 2),
    payment_due_at TIMESTAMP,
    funding_payment_reference VARCHAR(160) UNIQUE,
    funded_at TIMESTAMP,
    completed_at TIMESTAMP,
    cancellation_idempotency_key VARCHAR(255),
    cancellation_reason VARCHAR(500),
    cancellation_requested_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_waybill_creator FOREIGN KEY (creator_id) REFERENCES users (id),
    CONSTRAINT uq_waybill_creator_creation_key UNIQUE (creator_id, creation_idempotency_key),
    CONSTRAINT chk_waybill_creator_role CHECK (creator_role IN ('SENDER', 'RECIPIENT')),
    CONSTRAINT chk_waybill_payer_type CHECK (payer_type IN ('CREATOR', 'INVITED_PAYER')),
    CONSTRAINT chk_waybill_status CHECK (status IN (
        'AWAITING_PARTY_DETAILS',
        'AWAITING_QUOTE',
        'AWAITING_PAYMENT',
        'PAYMENT_REVIEW',
        'SHIPMENT_BOOKING',
        'READY_FOR_DELIVERY',
        'SHIPPING_FAILED',
        'CANCELLATION_PENDING',
        'REFUND_PENDING',
        'COMPLETED',
        'CANCELLED',
        'REFUNDED',
        'MANUAL_REVIEW'
    )),
    CONSTRAINT chk_waybill_payment_status CHECK (payment_status IN (
        'NOT_STARTED',
        'PENDING',
        'CONFIRMED',
        'REFUND_PENDING',
        'REFUNDED',
        'REVIEW'
    )),
    CONSTRAINT chk_waybill_declared_value CHECK (declared_value > 0),
    CONSTRAINT chk_waybill_provider_fee CHECK (provider_delivery_fee IS NULL OR provider_delivery_fee >= 0),
    CONSTRAINT chk_waybill_delivery_markup CHECK (delivery_markup IS NULL OR delivery_markup >= 0),
    CONSTRAINT chk_waybill_delivery_fee CHECK (delivery_fee IS NULL OR delivery_fee >= 0),
    CONSTRAINT chk_waybill_service_fee CHECK (service_fee IS NULL OR service_fee >= 0),
    CONSTRAINT chk_waybill_total_amount CHECK (total_amount IS NULL OR total_amount >= 0)
);

CREATE INDEX idx_waybills_creator_created
    ON waybills (creator_id, created_at, id);
CREATE INDEX idx_waybills_status_updated
    ON waybills (status, updated_at);
CREATE INDEX idx_waybills_payment_due
    ON waybills (payment_status, payment_due_at);

CREATE TABLE waybill_parties (
