CREATE TABLE waybill_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waybill_id BIGINT NOT NULL,
    kind VARCHAR(30) NOT NULL,
    target_party_role VARCHAR(20),
    can_pay BOOLEAN NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    access_token_hash VARCHAR(64) UNIQUE,
    staged_first_name VARCHAR(100),
    staged_last_name VARCHAR(100),
    staged_email VARCHAR(255),
    staged_phone_number VARCHAR(20),
    otp_challenge_id VARCHAR(64),
    otp_send_count INTEGER NOT NULL DEFAULT 0,
    otp_failed_attempt_count INTEGER NOT NULL DEFAULT 0,
    otp_locked_at TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP,
    details_completed_at TIMESTAMP,
    payment_completed_at TIMESTAMP,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_waybill_invitation_waybill FOREIGN KEY (waybill_id) REFERENCES waybills (id),
    CONSTRAINT fk_waybill_invitation_otp FOREIGN KEY (otp_challenge_id) REFERENCES otp_challenges (public_id),
    CONSTRAINT chk_waybill_invitation_kind CHECK (kind IN ('PARTY_COMPLETION', 'PAYMENT_ONLY')),
    CONSTRAINT chk_waybill_invitation_role CHECK (
        target_party_role IS NULL OR target_party_role IN ('SENDER', 'RECIPIENT')
    ),
    CONSTRAINT chk_waybill_invitation_target CHECK (
        (kind = 'PARTY_COMPLETION' AND target_party_role IS NOT NULL)
        OR (kind = 'PAYMENT_ONLY' AND target_party_role IS NULL)
    ),
    CONSTRAINT chk_waybill_invitation_otp_sends CHECK (otp_send_count >= 0),
    CONSTRAINT chk_waybill_invitation_otp_failures CHECK (otp_failed_attempt_count >= 0)
);

CREATE INDEX idx_waybill_invitations_active
    ON waybill_invitations (waybill_id, revoked_at, expires_at);
CREATE INDEX idx_waybill_invitations_otp
    ON waybill_invitations (otp_challenge_id);

