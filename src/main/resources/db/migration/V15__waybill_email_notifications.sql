CREATE TABLE waybill_email_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waybill_id BIGINT NOT NULL,
    party_id BIGINT NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    recipient_email VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    html_body TEXT,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP,
    dispatch_token UUID,
    first_attempt_at TIMESTAMP,
    failure_reason VARCHAR(500),
    sent_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_waybill_email_notification_waybill
        FOREIGN KEY (waybill_id) REFERENCES waybills (id),
    CONSTRAINT fk_waybill_email_notification_party
        FOREIGN KEY (party_id) REFERENCES waybill_parties (id),
    CONSTRAINT uq_waybill_email_notification_party_type
        UNIQUE (waybill_id, party_id, notification_type),
    CONSTRAINT chk_waybill_email_notification_type
        CHECK (notification_type IN ('AWAITING_PICKUP')),
    CONSTRAINT chk_waybill_email_notification_status
        CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT chk_waybill_email_notification_attempts
        CHECK (attempt_count >= 0)
);

CREATE INDEX idx_waybill_email_notifications_due
    ON waybill_email_notifications (status, next_attempt_at);
