CREATE TABLE order_tracking_access_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    token_ciphertext VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_tracking_access_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_order_tracking_token_hash
    ON order_tracking_access_tokens (token_hash);
CREATE INDEX idx_order_tracking_order_id
    ON order_tracking_access_tokens (order_id);

CREATE TABLE order_tracking_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    participant_role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    recipient_first_name VARCHAR(100) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    dispatch_token UUID,
    first_attempt_at TIMESTAMP WITH TIME ZONE,
    failure_reason VARCHAR(500),
    sent_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_tracking_notification_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uq_order_tracking_notification_role
        UNIQUE (order_id, participant_role),
    CONSTRAINT chk_order_tracking_notification_role
        CHECK (participant_role IN ('BUYER', 'VENDOR')),
    CONSTRAINT chk_order_tracking_notification_status
        CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT chk_order_tracking_notification_attempts
        CHECK (attempt_count >= 0)
);

CREATE INDEX idx_order_tracking_notifications_due
    ON order_tracking_notifications (status, next_attempt_at);
