CREATE TABLE chowdeck_control (
    id BIGINT PRIMARY KEY,
    configured_mode VARCHAR(16) NOT NULL,
    updated_by_user_id BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_chowdeck_control_singleton CHECK (id = 1),
    CONSTRAINT chk_chowdeck_control_mode CHECK (configured_mode IN ('OFF', 'SHADOW', 'ON')),
    CONSTRAINT chk_chowdeck_control_version CHECK (version >= 0),
    CONSTRAINT fk_chowdeck_control_updated_by
        FOREIGN KEY (updated_by_user_id) REFERENCES users (id)
);

INSERT INTO chowdeck_control (id, configured_mode, updated_at, version)
VALUES (1, 'OFF', CURRENT_TIMESTAMP, 0);

CREATE TABLE chowdeck_control_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_mode VARCHAR(16) NOT NULL,
    to_mode VARCHAR(16) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    changed_by_user_id BIGINT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    control_version BIGINT NOT NULL UNIQUE,
    CONSTRAINT chk_chowdeck_control_history_from_mode
        CHECK (from_mode IN ('OFF', 'SHADOW', 'ON')),
    CONSTRAINT chk_chowdeck_control_history_to_mode
        CHECK (to_mode IN ('OFF', 'SHADOW', 'ON')),
    CONSTRAINT chk_chowdeck_control_history_transition CHECK (from_mode <> to_mode),
    CONSTRAINT chk_chowdeck_control_history_reason CHECK (TRIM(reason) <> ''),
    CONSTRAINT chk_chowdeck_control_history_version CHECK (control_version > 0),
    CONSTRAINT fk_chowdeck_control_history_admin
        FOREIGN KEY (changed_by_user_id) REFERENCES users (id)
);

CREATE INDEX idx_chowdeck_control_history_changed
    ON chowdeck_control_history (control_version);
