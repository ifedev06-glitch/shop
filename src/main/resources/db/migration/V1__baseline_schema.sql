CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(255),
    lastname VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(50),
    created_at TIMESTAMP,
    transaction_pin VARCHAR(255),
    business_id BIGINT
);

CREATE UNIQUE INDEX idx_users_email ON users (email);

CREATE TABLE businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(255),
    description VARCHAR(255),
    phone_number VARCHAR(255),
    address VARCHAR(255),
    logo_url VARCHAR(255),
    signature_url VARCHAR(255),
    receipt_thank_you_message TEXT,
    owner_id BIGINT,
    created_at TIMESTAMP,
    CONSTRAINT fk_business_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE INDEX idx_businesses_owner_id ON businesses (owner_id);
ALTER TABLE users ADD CONSTRAINT fk_user_business FOREIGN KEY (business_id) REFERENCES businesses (id);

CREATE TABLE wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT,
    balance NUMERIC(38, 2) NOT NULL,
    total_withdrawn NUMERIC(38, 2) NOT NULL,
    currency VARCHAR(255) NOT NULL,
    status VARCHAR(50),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_wallet_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE UNIQUE INDEX idx_wallets_business_id ON wallets (business_id);

CREATE TABLE bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT,
    account_name VARCHAR(255),
    account_number VARCHAR(255),
    bank_code VARCHAR(255),
    bank_name VARCHAR(255),
    recipient_code VARCHAR(255),
    created_at TIMESTAMP,
    CONSTRAINT fk_bank_account_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE INDEX idx_bank_accounts_business_id ON bank_accounts (business_id);

CREATE TABLE withdrawals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT,
    amount NUMERIC(38, 2),
    reference VARCHAR(255) NOT NULL UNIQUE,
    transfer_code VARCHAR(255) UNIQUE,
    status VARCHAR(50),
    created_at TIMESTAMP,
    failure_reason VARCHAR(255),
    CONSTRAINT fk_withdrawal_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE INDEX idx_withdrawals_business_created ON withdrawals (business_id, created_at);
CREATE INDEX idx_withdrawals_transfer_code ON withdrawals (transfer_code);

CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT,
    type VARCHAR(50),
    amount NUMERIC(38, 2),
    balance_before NUMERIC(38, 2),
    balance_after NUMERIC(38, 2),
    reference VARCHAR(255),
    description VARCHAR(255),
    status VARCHAR(50),
    created_at TIMESTAMP,
    CONSTRAINT fk_wallet_transaction_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id)
);

CREATE INDEX idx_wallet_txns_wallet_id ON wallet_transactions (wallet_id);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT,
    title VARCHAR(255),
    description TEXT,
    amount NUMERIC(38, 2),
    category VARCHAR(255),
    expense_date DATE,
    created_at TIMESTAMP,
    CONSTRAINT fk_expense_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE INDEX idx_expenses_business_created ON expenses (business_id, created_at);

CREATE TABLE receipt_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT UNIQUE,
    show_customer_name BOOLEAN,
    show_customer_phone BOOLEAN,
    show_customer_address BOOLEAN,
    show_customer_email BOOLEAN,
    signature_enabled BOOLEAN,
    thank_you_message TEXT,
    CONSTRAINT fk_receipt_settings_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE INDEX idx_receipt_settings_business_id ON receipt_settings (business_id);

CREATE TABLE whatsapp_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL UNIQUE,
    phone_number VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP,
    CONSTRAINT fk_whatsapp_link_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE UNIQUE INDEX idx_whatsapp_links_business_id ON whatsapp_links (business_id);
CREATE UNIQUE INDEX idx_whatsapp_links_phone ON whatsapp_links (phone_number);

CREATE TABLE otp_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose VARCHAR(40) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    attempts INTEGER NOT NULL,
    consumed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_otp_purpose_subject_created ON otp_challenges (purpose, subject, created_at);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(255),
    business_id BIGINT,
    customer_name VARCHAR(255),
    email VARCHAR(255),
    phone_number VARCHAR(255),
    delivery_address TEXT,
    total_amount NUMERIC(38, 2),
    status VARCHAR(50),
    payment_status VARCHAR(255),
    settled BOOLEAN,
    created_at TIMESTAMP,
    payment_reference VARCHAR(255) UNIQUE,
    title VARCHAR(255),
    description TEXT,
    shipping_area VARCHAR(255),
    shipping_fee NUMERIC(38, 2),
    CONSTRAINT fk_order_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE INDEX idx_orders_order_number ON orders (order_number);
CREATE INDEX idx_orders_business_id ON orders (business_id);
CREATE INDEX idx_orders_status_payment_status ON orders (status, payment_status);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT UNIQUE,
    reference VARCHAR(255) NOT NULL UNIQUE,
    amount NUMERIC(38, 2),
    status VARCHAR(50),
    channel VARCHAR(255),
    paid_at TIMESTAMP,
    created_at TIMESTAMP,
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE UNIQUE INDEX idx_payments_reference ON payments (reference);
CREATE INDEX idx_payments_order_status ON payments (order_id, status);

CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(255) NOT NULL,
    request_path VARCHAR(255) NOT NULL,
    response_body TEXT,
    status_code INTEGER NOT NULL,
    created_at TIMESTAMP,
    CONSTRAINT uk_idempotency_key_path UNIQUE (idempotency_key, request_path)
);
