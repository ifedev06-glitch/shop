CREATE TABLE order_disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_disputes_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uq_order_disputes_order UNIQUE (order_id),
    CONSTRAINT chk_order_disputes_reason
        CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 2000),
    CONSTRAINT chk_order_disputes_status
        CHECK (status IN ('OPEN', 'UNDER_REVIEW', 'RESOLVED', 'REJECTED'))
);

CREATE INDEX idx_order_disputes_status_created
    ON order_disputes (status, created_at, id);

CREATE TABLE order_dispute_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id BIGINT NOT NULL,
    audience VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    recipient_first_name VARCHAR(100) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    dispatch_token UUID,
    first_attempt_at TIMESTAMP WITH TIME ZONE,
    failure_reason VARCHAR(500),
    sent_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_dispute_notifications_dispute
        FOREIGN KEY (dispute_id) REFERENCES order_disputes (id) ON DELETE CASCADE,
    CONSTRAINT uq_order_dispute_notification_audience UNIQUE (dispute_id, audience),
    CONSTRAINT chk_order_dispute_notification_audience
        CHECK (audience IN ('BUYER', 'VENDOR', 'OPERATIONS')),
    CONSTRAINT chk_order_dispute_notification_status
        CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_order_dispute_notification_attempts
        CHECK (attempt_count >= 0)
);

CREATE INDEX idx_order_dispute_notifications_due
    ON order_dispute_notifications (status, next_attempt_at, id);
