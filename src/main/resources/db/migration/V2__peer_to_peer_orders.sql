ALTER TABLE payments RENAME TO legacy_payments;
ALTER TABLE orders RENAME TO legacy_orders;

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    item_description TEXT NOT NULL,
    creator_role VARCHAR(20) NOT NULL,
    status VARCHAR(40) NOT NULL,
    share_token VARCHAR(64) NOT NULL UNIQUE,
    creator_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_creator FOREIGN KEY (creator_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX idx_orders_share_token ON orders (share_token);
CREATE INDEX idx_orders_creator_id ON orders (creator_id);
CREATE INDEX idx_orders_status ON orders (status);

CREATE TABLE order_counterparties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL,
    email VARCHAR(255) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    state VARCHAR(255) NOT NULL,
    country VARCHAR(255) NOT NULL,
    phone_verified BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_order_counterparty_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE UNIQUE INDEX idx_order_counterparties_order_id ON order_counterparties (order_id);
