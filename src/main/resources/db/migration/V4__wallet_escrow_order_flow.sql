CREATE TABLE wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    available_balance NUMERIC(38, 2) NOT NULL DEFAULT 0,
    processing_balance NUMERIC(38, 2) NOT NULL DEFAULT 0,
    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX idx_wallets_user_id ON wallets (user_id);

INSERT INTO wallets (
    user_id,
    available_balance,
    processing_balance,
    currency,
    created_at,
    updated_at,
    version
)
SELECT
    businesses.owner_id,
    SUM(legacy_wallets.balance),
    0,
    MIN(legacy_wallets.currency),
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP,
    0
FROM legacy_wallets
JOIN businesses ON businesses.id = legacy_wallets.business_id
WHERE businesses.owner_id IS NOT NULL
GROUP BY businesses.owner_id;

CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    reference VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    available_balance_before NUMERIC(38, 2) NOT NULL,
    available_balance_after NUMERIC(38, 2) NOT NULL,
    processing_balance_before NUMERIC(38, 2) NOT NULL,
    processing_balance_after NUMERIC(38, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_p2p_wallet_transaction_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_p2p_wallet_transaction_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE UNIQUE INDEX idx_wallet_transactions_order_id ON wallet_transactions (order_id);
CREATE UNIQUE INDEX idx_wallet_transactions_reference ON wallet_transactions (reference);

