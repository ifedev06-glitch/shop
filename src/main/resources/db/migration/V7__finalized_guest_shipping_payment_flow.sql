CREATE TABLE order_parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    weight_kg NUMERIC(12, 3) NOT NULL,
    length_cm NUMERIC(12, 2),
    width_cm NUMERIC(12, 2),
    height_cm NUMERIC(12, 2),
    quantity INTEGER NOT NULL DEFAULT 1,
    parcel_type VARCHAR(20) NOT NULL DEFAULT 'parcel',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_order_parcel_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

