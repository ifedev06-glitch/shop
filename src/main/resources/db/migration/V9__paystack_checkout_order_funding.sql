ALTER TABLE orders DROP CONSTRAINT chk_orders_funding_mode;
ALTER TABLE orders
    ADD CONSTRAINT chk_orders_funding_mode
    CHECK (funding_mode IN ('WALLET', 'PAYSTACK_CHECKOUT', 'DIRECT_DVA'));

UPDATE orders
SET funding_mode = 'PAYSTACK_CHECKOUT'
WHERE creator_role = 'VENDOR'
  AND funding_mode = 'DIRECT_DVA'
  AND payment_reference IS NULL
  AND payment_status = 'NOT_STARTED'
  AND status IN ('AWAITING_COUNTERPARTY', 'AWAITING_SHIPPING_RATE');

CREATE TABLE order_payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    provider VARCHAR(40) NOT NULL,
    provider_reference VARCHAR(160) NOT NULL,
    authorization_url TEXT NOT NULL,
    access_code VARCHAR(160) NOT NULL,
    customer_email VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_payment_attempt_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT chk_payment_attempt_amount CHECK (amount > 0),
    CONSTRAINT chk_payment_attempt_status
        CHECK (status IN ('INITIALIZED', 'SUCCESS', 'FAILED', 'ABANDONED', 'SUPERSEDED'))
);

CREATE UNIQUE INDEX idx_payment_attempts_reference
    ON order_payment_attempts (provider_reference);
CREATE INDEX idx_payment_attempts_order_status
    ON order_payment_attempts (order_id, status);
